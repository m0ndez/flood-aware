const FMT = { th: "th-TH", en: "en-GB" } as const;
export function fmtClock(ms: number, lang: Lang): string {
  return new Intl.DateTimeFormat(FMT[lang], { timeZone: "Asia/Bangkok", timeStyle: "medium" }).format(ms);
}

export function fmtTime(ms: number, lang: Lang): string {
  return new Intl.DateTimeFormat(FMT[lang], {
    timeZone: "Asia/Bangkok",
    dateStyle: "medium",
    timeStyle: "short",
  }).format(ms);
}
